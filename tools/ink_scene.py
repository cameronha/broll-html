"""Brush-ink line style on the founder-v9 poses -> scenes/ink-pitch.svg

usage: python3 tools/ink_scene.py
Look: black brush outlines (the stroke-width varies by part), solid black hair, white fills, one orange
accent, simple faces (dot eyes, line mouths, L noses, stubble dots). Limbs are "double strokes": a wide
black stroke under a narrower fill stroke on the same path, so overlapping limbs keep clean outlines.
Each piece has the #ink wobble filter; svgpieces re-seeds its turbulence per variant, so the lines boil.
"""
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INK, PAPER, ORANGE = "#141414", "#FFFFFF", "#ED7239"
LINE = 8   # outline weight in scene units


def limb(d, w, fill, line=LINE):
    return (f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="{w + 2 * line}" stroke-linecap="round" stroke-linejoin="round"/>'
            f'<path d="{d}" fill="none" stroke="{fill}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>')


def o(tag, fill=PAPER, w=LINE, **a):
    attrs = " ".join(f'{k.replace("_", "-")}="{v}"' for k, v in a.items())
    return f'<{tag} {attrs} fill="{fill}" stroke="{INK}" stroke-width="{w}" stroke-linejoin="round"/>'


def line(d, w=6):
    return f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>'


def dot(x, y, r):
    return f'<circle cx="{x}" cy="{y}" r="{r}" fill="{INK}"/>'


def group(gid, body, rig=""):
    return f'  <g id="{gid}"{rig} filter="url(#ink)">{body}</g>\n'


