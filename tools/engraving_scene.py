"""Neoclassical engraving look (white robed figures, black line hatching, one flat red, palmette border)
-> scenes/engraving-pitch.svg

usage: python3 tools/engraving_scene.py
Reference: a Greek-revival book cover (white figures engraved on flat red). The stick looks swap
via set_look in stick_scene.py; this one needs robed figures, so it has its own poses. Shadows are
shapes filled with a hatch <pattern>; folds are thin curves; limbs reuse the stick double stroke.
"""
import os
import stick_scene as S

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INK, WHITE, RED = "#141414", "#FFFFFF", "#E0263A"
S.INK, S.PAPER = INK, WHITE


def shape(d, fill=WHITE, w=3.2):
    if fill.startswith("url("):     # hatch over white, so the red does not show through the lines
        return f'<path d="{d}" fill="{WHITE}"/><path d="{d}" fill="{fill}" stroke="{INK}" stroke-width="{w:g}" stroke-linejoin="round"/>'
    return f'<path d="{d}" fill="{fill}" stroke="{INK}" stroke-width="{w:g}" stroke-linejoin="round"/>'


def shade(d, dense=False):
    """A hatched shadow region, no outline."""
    return f'<path d="{d}" fill="url(#{"hatch2" if dense else "hatch"})"/>'


def ln(d, w=2.2):
    return S.line(d, w)


def folds(top, bot, n, bend=0, w=1.8):
    """n fold lines from the segment `top` to the segment `bot`, each bowed sideways by `bend`."""
    (ax, ay), (bx, by) = top
    (cx, cy), (dx, dy) = bot
    out = ""
    for i in range(n):
        t = (i + 0.5) / n
        x0, y0, x1, y1 = ax + (bx - ax) * t, ay + (by - ay) * t, cx + (dx - cx) * t, cy + (dy - cy) * t
        out += ln(f"M{x0:.0f} {y0:.0f} Q{(x0 + x1) / 2 + bend * (1 - 2 * abs(t - 0.5)):.0f} {(y0 + y1) / 2:.0f} {x1:.0f} {y1:.0f}", w)
    return out


def limb(d, w=24):
    return S.tube(d, w, 3.2)


def border(y):
    """Palmette frieze: white band, black rules, black anthemion fans with red centers."""
    o = f'<rect x="0" y="{y}" width="1080" height="84" fill="{WHITE}"/>' + ln(f"M0 {y + 4} L1080 {y + 4} M0 {y + 80} L1080 {y + 80}", 5)
    for i in range(10):
        x, c = 54 + i * 108, y + 42
        fan = f"M{x - 34} {c + 26} Q{x - 46} {c - 30} {x} {c - 32} Q{x + 46} {c - 30} {x + 34} {c + 26} Q{x} {c + 8} {x - 34} {c + 26} Z"
        o += f'<path d="{fan}" fill="{INK}"/>'
        o += "".join(ln(f"M{x} {c + 14} L{x + dx} {c - 24}", 2.4).replace(INK, WHITE) for dx in (-26, -13, 0, 13, 26))
        o += f'<circle cx="{x}" cy="{c + 16}" r="5" fill="{RED}"/>'
        o += ln(f"M{x + 40} {c + 20} q14 -2 14 -14 q0 -10 -8 -8", 2.4) + ln(f"M{x + 68} {c + 20} q-14 -2 -14 -14 q0 -10 8 -8", 2.4)
    return o


